def _visible(html: str) -> str:
    parts = re.findall(r"<p\b[^>]*>(.*?)</p>", html, re.S) or [html]
    text = " ¶ ".join(re.sub(r"<[^>]+>", "", p).strip() for p in parts)
    return re.sub(r"\s+", " ", text).strip()


def _normalized(text: str) -> str:
    # Вид тире (—, –, ─) здесь не проверяется: это решают другие правила.
    return re.sub(r"\s+", " ", re.sub(r"[–—─−]", "—", text)).strip()


@pytest.mark.parametrize(
    ("name", "html", "expected"),
    [
        pytest.param(*case, id=case[0],
                     marks=[pytest.mark.xfail(strict=True, reason=STEP_2[case[0]])] if case[0] in STEP_2 else [])
        for case in CASES
    ],
)
def test_developer_table(name, html, expected):
    assert _normalized(_visible(text_utils.prettify_html(html))) == _normalized(expected)


def test_hyphen_attached_to_word_before_comma_survives():
    out = _visible(text_utils.prettify_html(
        "<p>Другие уничтожают одно-, двух- и трехочковых роботов.</p>"
    ))
    assert "…" not in out, out
    assert "одно-," in out, out


# --- подготовка оригинала для модели ---

def test_source_split_by_br_gets_no_ellipsis_markers():
    # У иероглифов isalpha() истинно, и метка «…» вставала почти на каждой
    # строке, разрезанной по <br>; модель её переводила.
    out = text_utils.prettify_html_for_ai("<p>第一行<br/>第二行</p>")
    assert "…" not in out, out
    assert "第一行" in out and "第二行" in out, out


def test_source_prep_never_adds_ellipses():
    @settings(max_examples=150, deadline=None, suppress_health_check=[HealthCheck.too_slow])
    @given(
        value=st.lists(
            st.tuples(st.sampled_from(["p", "div", "em"]),
                      st.text(alphabet="«»–—─-.,!? …абвНетZx第行\n", max_size=40)),
            max_size=5,
        ).map(lambda blocks: "".join(f"<{t}>{b.replace(chr(10), '<br/>')}</{t}>" for t, b in blocks))
    )
    def check(value):
        out = text_utils.prettify_html_for_ai(value)
        assert out.count("…") <= len(re.findall(r"…|\.{2,}", value)), (value, out)

    check()
